"""Reproducible authored curriculum; no human participants or weight training."""
import itertools
import json
from pathlib import Path
import sys
ROOT=Path(__file__).resolve().parents[1]
sys.path.insert(0,str(ROOT))
from rio_evidence.tutor import answer


def build():
    cases=[]
    for mode,design,build_minutes,test_minutes,deliver in itertools.product(
            ['parallel','tests_after_build','build_after_tests','independent_tests'],
            [3,5],[10,20],[5,15,25,35],[2,5]):
        tasks=[{'id':'Design'}, {'id':'Build','depends_on':['Design']},
               {'id':'Tests','depends_on':['Design']},
               {'id':'Deliver','depends_on':['Build','Tests']}]
        if mode=='tests_after_build':tasks[2]['depends_on']=['Build']
        if mode=='build_after_tests':tasks[1]['depends_on']=['Tests']
        if mode=='independent_tests':tasks[2]['depends_on']=[]
        case={'case_id':f'SCHED-{len(cases)+1:03d}', 'topology':mode,
              'tasks':tasks,'durations':dict(Design=design,Build=build_minutes,Tests=test_minutes,Deliver=deliver),
              'split':'holdout' if len(cases)%5==0 else 'practice',
              'provenance':'AUTHORED_SYNTHETIC_NOT_HUMAN_USAGE'}
        case['reference']=answer(case);cases.append(case)
    return cases


if __name__=='__main__':
    cases=build()
    (ROOT/'training/answer_matrix.jsonl').write_text(''.join(json.dumps(c)+'\n' for c in cases))
    lines=['# Scheduling answer matrix','',
           'Authored synthetic scenarios. Reference answers are computed, not generated by an LLM.',
           'Holdout is a fixed practice partition, not a secret independent benchmark.','',
           '| Case | Split | Topology | Design / Build / Tests / Deliver | Critical path | Minutes | Serial |',
           '| --- | --- | --- | --- | --- | ---: | ---: |']
    for c in cases:
        a=c['reference'];lines.append('| '+ ' | '.join([c['case_id'],c['split'],c['topology'],
            ' / '.join(map(str,c['durations'].values())), ' → '.join(a['path']),
            str(a['critical_path_minutes']),str(a['single_worker_minutes'])])+' |')
    (ROOT/'training/ANSWER_MATRIX.md').write_text('\n'.join(lines)+'\n')
    print(json.dumps({'cases':len(cases),'practice':sum(c['split']=='practice' for c in cases),
                      'holdout':sum(c['split']=='holdout' for c in cases)}))
