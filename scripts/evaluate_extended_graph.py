"""Deterministic enumeration, authored within this project, not external."""
import importlib.util
import json
import statistics
import sys
import time
from pathlib import Path
ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from rio_evidence.graph_copy import extract_graph
from rio_evidence.extended_graph import extract_extended_graph
from rio_evidence.semantic_gate import grade

spec = importlib.util.spec_from_file_location("h09_test_generator", ROOT/"tests/test_extended_graph.py")
mod = importlib.util.module_from_spec(spec)
spec.loader.exec_module(mod)

def run():
    baseline = candidate = 0
    a_times, b_times = [], []
    for mask in range(1024):
        for family in range(4):
            text, reference = mod.generate(mask, 5, family)
            start = time.perf_counter_ns()
            left = extract_graph(text)
            a_times.append((time.perf_counter_ns() - start)/1e6)
            start = time.perf_counter_ns()
            right = extract_extended_graph(text)
            b_times.append((time.perf_counter_ns() - start)/1e6)
            baseline += grade(left["graph"], reference)["pass"]
            candidate += grade(right["graph"], reference)["pass"]
    cases = [json.loads(x) for x in (ROOT/"training/extraction_dev.jsonl").read_text().splitlines() if x.strip()]
    preserved = sum(grade(extract_graph(c["text"])["graph"],c["expected"]) ==
                    grade(extract_extended_graph(c["text"])["graph"],c["expected"]) for c in cases)
    report = {
        "scope": "PROJECT_AUTHORED_EXHAUSTIVE_FIVE_NODE_FORWARD_EDGE_GRAMMARS",
        "forward_edge_choices": 10,
        "exhaustive_topologies": 1024,
        "grammars": 4, "paired_cases": 4096,
        "baseline_exact": baseline, "candidate_exact": candidate,
        "exact_delta": candidate-baseline,
        "legacy_dev_preserved": preserved, "legacy_dev_cases": len(cases),
        "baseline_median_ms": statistics.median(a_times),
        "candidate_median_ms": statistics.median(b_times),
        "financial_cost": "UNKNOWN",
        "independent_external_data": False,
        "neural_calls": 0,
        "limits": ["Synthetic cases generated by this project; not hidden testing.",
                   "Only 1024 forward DAGs with five ordered IDs, four authored formats.",
                   "Runtime medians vary with machine; not an external cost certificate."]
    }
    if (baseline,candidate,preserved,len(cases)) != (0,4096,94,94):
        raise SystemExit("H09_EXHAUSTIVE_GATE_FAILED")
    return report
if __name__=="__main__":
    print(json.dumps(run(),sort_keys=True,indent=2))
